# ── Shared helpers ──────────────────────────────────────────────────────────
def raw_pairs(csv):
    """Yields (plasma_index, plasma_row, bg_row, wl, P, B) with the documented pairing rule."""
    df = pd.read_csv(csv)
    cols = df.columns[6:-8]
    wl = cols.astype(float).to_numpy()
    last, last_row, k = None, None, 0
    for i, r in df.iterrows():
        f, l = int(r["Force Reset Status"]), int(r["Laser Fire Status"])
        if (f, l) == (1, 0):
            last, last_row = r, i + 1
        elif (f, l) == (0, 1):
            k += 1
            if last is not None:
                yield k, r, last, last_row, wl, r[cols].to_numpy(float), last[cols].to_numpy(float)


def noise_sigma(wl, y):
    m = (wl >= S["noise_min"]) & (wl <= S["noise_max"])
    return float(np.std(y[m], ddof=S["sigma_ddof"]))


def detect(wl, y):
    """Calibrated-range peaks: prominence >= 3 sigma (560-580 nm, ddof=0), >= 5 channels apart."""
    sig = noise_sigma(wl, y)
    c = (wl >= S["cal_min"]) & (wl <= S["cal_max"])
    idx, props = find_peaks(y[c], prominence=S["prominence_sigma"] * sig, distance=S["peak_distance_channels"])
    return np.flatnonzero(c)[idx], props["prominences"], sig


def n_matched(peak_wl, ref):
    if len(peak_wl) == 0:
        return 0
    return int((np.abs(peak_wl[:, None] - ref[None, :]) < S["match_tol_nm"]).any(axis=1).sum())


def n_lines_hit(peak_wl, ref):
    if len(peak_wl) == 0:
        return 0
    return int((np.abs(peak_wl[:, None] - ref[None, :]) < S["match_tol_nm"]).any(axis=0).sum())


def cleaned(obs, date):
    d = pd.read_csv(PROC / date / obs / f"{obs}_cleaned.csv")
    return {m: g.sort_values("Wavelength_nm") for m, g in d.groupby("Measurement_ID")}


# ── A. Worked example ──────────────────────────────────────────────────────
def section_a():
    obs = S["worked_obs"]
    cl = cleaned(obs, "20230825")
    rows, win = [], []
    for k, pr, br, bg_row, wl, P, B in raw_pairs(RAW / "20230825" / obs / f"{obs}.csv"):
        c = cl[k].Cleaned_Intensity.to_numpy()
        R = P - B
        assert np.array_equal(np.maximum(R, 0), c), f"ID {k}: cleaned != max(0, P-B)"
        cal = (wl >= S["cal_min"]) & (wl <= S["cal_max"])
        rows.append({"measurement_id": k, "plasma_row": int(pr.name) + 1, "background_row": bg_row,
                     "plasma_time": pr["Time"], "background_time": br["Time"],
                     "mean_full": c.mean(), "std_full": c.std(), "max_full": c.max(),
                     "mean_cal": c[cal].mean(), "std_cal": c[cal].std(), "max_cal": c[cal].max(),
                     "clip_frac_full": float((R < 0).mean()), "clip_frac_cal": float((R[cal] < 0).mean()),
                     "zero_frac_full_old_definition": float((c == 0).mean()),
                     "laser_energy": pr["Laser Energy"]})
        m = (wl >= S["noise_min"]) & (wl <= S["noise_max"])
        p, b, r = P[m], B[m], R[m]
        cov = float(np.cov(p, b, ddof=0)[0, 1])
        win.append({"measurement_id": k, "n_channels": int(m.sum()),
                    "raw_mean": p.mean(), "raw_std": p.std(), "bg_mean": b.mean(), "bg_std": b.std(),
                    "residual_mean": r.mean(), "residual_std": r.std(),
                    "clean_mean": c[m].mean(), "clean_std": c[m].std(),
                    "raw_over_clean_mean": p.mean() / c[m].mean(),
                    "clean_std_over_raw_std": c[m].std() / p.std(),
                    "residual_std_over_raw_std": r.std() / p.std(),
                    "cov_PB": cov, "corr_PB": float(np.corrcoef(p, b)[0, 1]),
                    "predicted_residual_std": math.sqrt(p.var() + b.var() - 2 * cov),
                    "predicted_ratio_if_independent": math.sqrt(p.var() + b.var()) / p.std(),
                    "negative_frac_window": float((r < 0).mean())})
    wr(pd.DataFrame(rows), "A_worked_example_ids.csv")
    wr(pd.DataFrame(win), "A_worked_example_window_560_580.csv")


# ── B. Archive clipping ────────────────────────────────────────────────────
def section_b(audit_rows):
    rows, spectra = [], {}
    for csv in sorted(RAW.glob("*/*/*.csv")):
        if csv.stem.split("_")[-1].isdigit():
            continue
        for k, pr, br, bg_row, wl, P, B in raw_pairs(csv):
            R = P - B
            C = np.maximum(R, 0)
            cal = (wl >= S["cal_min"]) & (wl <= S["cal_max"])
            nm = (wl >= S["noise_min"]) & (wl <= S["noise_max"])
            pk, prom, sig = detect(wl, C)
            mad = 1.4826 * np.median(np.abs(R[nm] - np.median(R[nm])))
            rows.append({"product": csv.stem, "measurement_id": k, "background_row": bg_row,
                         "pair_gap_s": (pd.to_datetime(pr["Time"]) - pd.to_datetime(br["Time"])).total_seconds(),
                         "n_channels_full": len(wl), "n_channels_cal": int(cal.sum()),
                         "clip_frac_full": float((R < 0).mean()), "clip_frac_cal": float((R[cal] < 0).mean()),
                         "zero_frac_full_old_definition": float((C == 0).mean()),
                         "mean_clean_cal": float(C[cal].mean()), "median_residual_cal": float(np.median(R[cal])),
                         "plasma_mean_cal": float(P[cal].mean()), "bg_mean_cal": float(B[cal].mean()),
                         "noise_sigma_clean": sig, "n_peaks_3sigma": len(pk),
                         "peak_snr_robust": float((C[cal].max() - np.median(R[cal])) / mad) if mad > 0 else np.nan,
                         "laser_energy": pr["Laser Energy"], "integration_time_us": pr["Integration Time"],
                         "number_of_pulses": pr["Number of Pulses"], "delay_time_us": pr["Delay Time"]})
            spectra[(csv.stem, k)] = (wl, C)
    sh = wr(pd.DataFrame(rows), "B_archive_paired_shots.csv")
    thr = []
    for col in ["clip_frac_full", "clip_frac_cal", "zero_frac_full_old_definition"]:
        for t in S["clip_thresholds"]:
            n = int((sh[col] > t).sum())
            thr.append({"definition": col, "threshold": t, "flagged": n, "flagged_pct": 100 * n / len(sh),
                        "not_flagged": len(sh) - n})
    wr(pd.DataFrame(thr), "B_clip_threshold_sensitivity.csv")
    cor = []
    for q in ["mean_clean_cal", "median_residual_cal", "plasma_mean_cal", "bg_mean_cal", "n_peaks_3sigma",
              "peak_snr_robust", "laser_energy", "integration_time_us", "number_of_pulses"]:
        ok = sh[["clip_frac_full", q]].dropna()
        rho, p = spearmanr(ok.clip_frac_full, ok[q])
        lo, hi = ok[ok.clip_frac_full <= S["clip_flag"]][q], ok[ok.clip_frac_full > S["clip_flag"]][q]
        cor.append({"measure": q, "n": len(ok), "spearman_rho_vs_clip_full": rho, "p_value": p,
                    "median_unflagged": lo.median(), "median_flagged": hi.median()})
    wr(pd.DataFrame(cor), "B_clip_vs_quality_measures.csv")
    gaps = sh.pair_gap_s.value_counts().sort_index()
    wr(pd.DataFrame({"pair_gap_s": gaps.index, "n_shots": gaps.values}), "B_pair_gap_distribution.csv")
    return sh, spectra


# ── C. Downsampling ────────────────────────────────────────────────────────
def idx_of(wl, out):
    o = np.array([p["wavelength_nm"] for p in out["data"]])
    return np.searchsorted(wl, o)   # outputs are exact input wavelengths


def prod(wl, y, k, targets=None, threshold=None):
    data = np.column_stack([wl, y, y])
    # explicit budget via the API's `proportion`: int(2094 * (t + 0.5) / 2094) == t
    prop = None if threshold is None else (threshold + 0.5) / 2094
    out = lttb_downsample(data, zoom_level=k, lambda_min=wl[0], lambda_max=wl[-1],
                          target_wavelengths=None if targets is None else list(targets), proportion=prop)
    return idx_of(wl, out)


def uniform(n, t):
    return np.unique(np.round(np.linspace(0, n - 1, t)).astype(int))


def maxbin(y, t):
    e = np.linspace(0, len(y), t + 1).astype(int)
    return np.array(sorted({int(lo + np.argmax(y[lo:hi])) for lo, hi in zip(e[:-1], e[1:]) if hi > lo}))


def score(wl, y, idx, peaks, nist_peaks):
    idx = np.unique(idx)
    rmse = float(np.sqrt(np.mean((y - np.interp(wl, wl[idx], y[idx])) ** 2)))
    s = set(idx.tolist())
    ret = lambda P: 100.0 * np.mean([p in s for p in P]) if len(P) else np.nan
    return {"n_out": len(idx), "rmse": rmse, "local_max_ret_pct": ret(peaks), "nist_matched_ret_pct": ret(nist_peaks)}


def section_c():
    obs = S["worked_obs"]
    cl = cleaned(obs, "20230825")
    nist_in = NIST_CAL.ref_nm.to_numpy()
    rows = []
    for mid in S["eval_ids"]:
        g = cl[mid]
        wl_full, y_full = g.Wavelength_nm.to_numpy(), g.Cleaned_Intensity.to_numpy()
        pk_full, _, _ = detect(wl_full, y_full)
        for rng in ["calibrated", "full_stored"]:
            if rng == "calibrated":
                c = (wl_full >= S["cal_min"]) & (wl_full <= S["cal_max"])
                wl, y = wl_full[c], y_full[c]
                pk = np.searchsorted(wl, wl_full[pk_full])
            else:
                wl, y, pk = wl_full, y_full, pk_full
            matched = pk[(np.abs(wl[pk][:, None] - nist_in[None, :]) < S["match_tol_nm"]).any(axis=1)]
            n = len(wl)
            for k in S["zoom_levels"]:
                T = min(2094, int(2094 * 2 ** -k))
                lt = prod(wl, y, k)
                lp = prod(wl, y, k, targets=wl[pk])
                ln = prod(wl, y, k, targets=nist_in)
                # LTTB+Peaks squeezed into the same budget T: largest LTTB size whose union with the peaks <= T
                t = T
                while t > 3 and len(np.union1d(prod(wl, y, k, threshold=t), pk)) > T:
                    t -= 1
                lp_eq = np.union1d(prod(wl, y, k, threshold=t), pk) if len(pk) < T else None
                B = len(np.unique(lp))
                variants = {
                    ("Uniform", "fixed T"): uniform(n, T), ("Max-binning", "fixed T"): maxbin(y, T),
                    ("LTTB", "fixed T"): lt, ("LTTB+NIST targets (web console)", "T + targets"): ln,
                    ("LTTB+Peaks", "T + peaks"): lp,
                    ("Uniform", "matched to LTTB+Peaks size"): uniform(n, B),
                    ("Max-binning", "matched to LTTB+Peaks size"): maxbin(y, B),
                    ("LTTB", "matched to LTTB+Peaks size"): prod(wl, y, k, threshold=B),
                }
                if lp_eq is not None:
                    variants[("LTTB+Peaks", "total <= T")] = lp_eq
                for (alg, budget), idx in variants.items():
                    rows.append({"measurement_id": mid, "range": rng, "n_channels": n, "zoom_k": k, "T": T,
                                 "algorithm": alg, "budget": budget, "n_peaks": len(pk),
                                 "n_nist_matched_peaks": len(matched),
                                 **score(wl, y, idx, pk, matched),
                                 "density_pct": 100 * len(np.unique(idx)) / n})
    df = wr(pd.DataFrame(rows), "C_downsampling.csv")
    # check the documented size bound |S_final| <= |S_LTTB| + |targets|
    lt = df[(df.algorithm == "LTTB") & (df.budget == "fixed T")].set_index(["measurement_id", "range", "zoom_k"]).n_out
    lp = df[(df.algorithm == "LTTB+Peaks") & (df.budget == "T + peaks")].set_index(["measurement_id", "range", "zoom_k"])
    assert (lp.n_out <= lt + lp.n_peaks).all()


# ── D. NIST candidates + null model ────────────────────────────────────────
def shifts(n, seed):
    rng = np.random.default_rng(seed)
    return rng.uniform(S["null_shift_min_nm"], S["null_shift_max_nm"], n) * rng.choice([-1, 1], n)


def wrap(ref, s):
    """Sensitivity variant: shifted lines that leave 220-800 nm re-enter from the other end."""
    w = S["cal_max"] - S["cal_min"]
    return S["cal_min"] + np.mod(ref + s - S["cal_min"], w)


def null_counts(peak_wl, sh, boundary):
    ref = NIST_CAL.ref_nm.to_numpy()
    return np.array([n_matched(peak_wl, ref + s if boundary == "drop" else wrap(ref, s)) for s in sh])


def p_emp(null, obs):
    return (1 + int((null >= obs).sum())) / (1 + len(null))


def section_d(shots, spectra):
    ref = NIST_CAL.ref_nm.to_numpy()
    sh = shifts(S["null_draws"], S["null_seed"])
    obs = S["worked_obs"]
    cl = cleaned(obs, "20230825")
    per_line, worked, null_dump = [], [], {}
    for mid in S["eval_ids"]:
        g = cl[mid]
        wl, y = g.Wavelength_nm.to_numpy(), g.Cleaned_Intensity.to_numpy()
        pk, prom, sig = detect(wl, y)
        for p, pr in zip(pk, prom):
            d = wl[p] - NIST.ref_nm.to_numpy()
            near = NIST[np.abs(d) < S["fwhm_upper_bound_nm"]]
            cand = NIST[np.abs(d) < S["match_tol_nm"]]
            if len(cand) == 0:
                continue
            best = cand.iloc[np.argmin(np.abs(wl[p] - cand.ref_nm.to_numpy()))]
            per_line.append({"measurement_id": mid, "observed_nm": wl[p], "channel_index": int(p),
                             "intensity": y[p], "prominence": pr, "prominence_over_sigma": pr / sig,
                             "nearest_ref_species": best.species, "nearest_ref_nm": best.ref_nm,
                             "offset_obs_minus_ref_nm": wl[p] - best.ref_nm,
                             "refs_within_tol": "; ".join(f"{r.species} {r.ref_nm:.2f}" for r in cand.itertuples()),
                             "refs_within_1p1nm": "; ".join(f"{r.species} {r.ref_nm:.2f}" for r in near.itertuples()),
                             "possible_blend": len(near) > 1})
        o = n_matched(wl[pk], ref)
        rec = {"measurement_id": mid, "n_peaks": len(pk), "sigma": sig, "prominence_threshold": 3 * sig,
               "observed_matched_peaks": o, "observed_lines_hit": n_lines_hit(wl[pk], ref),
               "lines_in_list": len(ref), "match_rate_pct": 100 * o / len(pk)}
        for b in ["drop", "wrap"]:
            null = null_counts(wl[pk], sh, b)
            null_dump[f"id{mid}_{b}"] = null
            rec.update({f"null_mean_{b}": null.mean(), f"null_p95_{b}": np.percentile(null, 95),
                        f"p_{b}": p_emp(null, o)})
        worked.append(rec)
    wr(pd.DataFrame(per_line), "D_per_line_candidates.csv")
    wr(pd.DataFrame(worked), "D_null_worked_example.csv")

    # Archive aggregate over paired shots: all, and clip_frac_full <= 0.5
    sh_arch = shifts(S["archive_null_draws"], S["archive_null_seed"])
    pks = {key: wl[detect(wl, C)[0]] for key, (wl, C) in spectra.items()}
    sub_axis = None
    sf = V2 / "outputs" / "archive_audit" / "subfiles.csv"
    agg = []
    for label, keep in [("all_paired", shots.index), ("clip_frac_full<=0.5", shots[shots.clip_frac_full <= 0.5].index)]:
        keys = list(zip(shots.loc[keep, "product"], shots.loc[keep, "measurement_id"]))
        obs_total = sum(n_matched(pks[k], ref) for k in keys)
        lines_total = sum(n_lines_hit(pks[k], ref) for k in keys)
        null = np.array([sum(n_matched(pks[k], ref + s) for k in keys) for s in sh_arch])
        null_dump[f"archive_{label}"] = null
        agg.append({"set": label, "n_spectra": len(keys), "n_peaks": sum(len(pks[k]) for k in keys),
                    "observed_matched_peaks": obs_total, "observed_line_hits": lines_total,
                    "null_draws": len(sh_arch), "null_mean": null.mean(), "null_p95": np.percentile(null, 95),
                    "p_drop": p_emp(null, obs_total)})
    wr(pd.DataFrame(agg), "D_null_archive.csv")
    np.savez_compressed(OUT / "D_null_distributions.npz", shifts_worked=sh, shifts_archive=sh_arch, **null_dump)

    # Sensitivity: same detected channels, labelled with the per-shot subfile wavelength axis
    if sf.exists():
        f = pd.read_csv(sf)
        one = f.iloc[0]
        sub = pd.read_csv(RAW / one["product"].split("_")[3][:8] / one["product"] / one["subfile"]).iloc[:, 0].to_numpy()
        parent_wl = next(iter(spectra.values()))[0]
        keys = list(zip(shots["product"], shots["measurement_id"]))
        pk_idx = {k: detect(*spectra[k])[0] for k in keys}
        axis = []
        for name, ax in [("parent_table_axis", parent_wl), ("subfile_axis", sub)]:
            o = sum(n_matched(ax[pk_idx[k]], ref) for k in keys)
            null = np.array([sum(n_matched(ax[pk_idx[k]], ref + s) for k in keys)
                             for s in sh_arch[:S["axis_null_draws"]]])
            null_dump[f"axis_{name}"] = null
            axis.append({"axis": name, "n_spectra": len(keys), "observed_matched_peaks": o,
                         "null_mean": null.mean(), "null_p95": np.percentile(null, 95), "p_drop": p_emp(null, o),
                         "null_draws": len(null)})
        wr(pd.DataFrame(axis), "D_wavelength_axis_sensitivity.csv")
        np.savez_compressed(OUT / "D_null_distributions.npz", shifts_worked=sh, shifts_archive=sh_arch, **null_dump)

    # One authoritative table for manuscript, report and response: exceedances k = #{null >= observed}
    summary = []
    for r in worked:
        summary.append((f"ID {r['measurement_id']}", f"id{r['measurement_id']}_drop", r["observed_matched_peaks"]))
    for a in agg:
        summary.append((f"Archive, parent axis, {a['set']}", f"archive_{a['set']}", a["observed_matched_peaks"]))
    for a in (axis if sf.exists() else []):
        summary.append((f"Archive, {a['axis']} (axis sensitivity)", f"axis_{a['axis']}", a["observed_matched_peaks"]))
    wr(pd.DataFrame([{"evaluation": e, "draws": len(null_dump[key]), "observed": o,
                      "null_mean": null_dump[key].mean(), "exceedances": int((null_dump[key] >= o).sum()),
                      "p_empirical": p_emp(null_dump[key], o)} for e, key, o in summary]), "D_null_summary.csv")


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "settings.json").write_text(json.dumps(S, indent=2))
    section_a()
    shots, spectra = section_b(None)
    section_c()
    section_d(shots, spectra)
    print("analysis outputs ->", OUT)


if __name__ == "__main__":
    main()
